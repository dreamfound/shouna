package com.dream.shouna.data.remote.ai

/**
 * AI 调用的**功能场景** —— 决定 system prompt 里「功能段」用哪一套（`V2-AI-PRD` `V2-FR-16`
 * 的「提示词**按功能各一套**」）。
 *
 * 三个取值与「通道」的关系（`V2-AI-PRD` §3 的名词口径）：
 * - [TEXT_INPUT]：**文字与语音共用一套**。语音只是把话变成文本（`V2-FR-10`），进模型的输入
 *   完全一样；按通道拆成两套只会得到两份内容重复的提示词，而能力槽口径也明确「文本槽服务
 *   文字与语音通道」（`V2-AI-PRD` §3）。
 * - [PHOTO_INPUT]：拍照识别（`V2-FR-11`）。按 `V2-FR-13`「位置先定后用」，这一套的 prompt
 *   **不含位置段**，模型的返回也**不含位置字段**。
 * - [QUERY]：查询侧。**本版没有文案、没有调用方** —— `V2-AI-PRD` §7 明确「本版不引入 AI
 *   查询」。留这个枚举位是为了让 `V2-FR-16` 的「录入 / 图片 / 查询」三档在类型上可见；
 *   §7 的三个问句有答案后，只需在 [AiPrompt] 里补一段功能段文案，其余四段不动。
 */
enum class AiScene {
    /** 录入 · 文字与语音通道（`V2-FR-02` / `V2-FR-10`）。 */
    TEXT_INPUT,

    /** 录入 · 照片通道（`V2-FR-11`）。 */
    PHOTO_INPUT,

    /** 查询侧（`V2-FR-16` 列出、`V2-AI-PRD` §7 本版不做文案）。 */
    QUERY,
}
