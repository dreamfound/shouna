package com.dream.shouna.data.remote.ai

/**
 * AI 调用的**功能场景** —— 决定 system prompt 里「功能段」用哪一套（`V2-AI-PRD` `V2-FR-16`
 * 的「提示词**按功能各一套**」）。
 *
 * 四个取值与「通道」的关系（`V2-AI-PRD` §3 的名词口径）：
 * - [TEXT_INPUT]：录入页（P-ADD）名称框里**打字**的那一路（`V2-FR-02`）。位置有表单兜底
 *   （用户已选位置），模型的注意力放在「格式化 + 补分类」。
 * - [VOICE_INPUT]：语音 AI 录入页（P-VOICE-AI，`V2-FR-10`）。输入是**语音转文字**的一整句话，
 *   位置**没有兜底**（只能从这句话里来，且本地不新建），故**单独一套**
 *   （2026-10-09 由「与文字通道共用」改，用户口径）。
 * 【2026-10-10 停用 · 注释保留】曾另立一个 `VOICE_AUDIO`（同一页的**录音**形态 —— 输入是一段
 * WAV 录音、由模型自己听完再拆，位置口径与 [VOICE_INPUT] 相同）。**平台不受理音频输入**
 * （`content` part 只认 `text` / `image_url` / `file`），故该场景连同整条录音链路一并注释、未删；
 * 原因与接回方式见 `data/local/audio/AudioRecorder.kt` 的文件头。
 * - [PHOTO_INPUT]：拍照识别（`V2-FR-11`）。按 `V2-FR-13`「位置先定后用」，这一套的 prompt
 *   **不含位置段**，模型的返回也**不含位置字段**。
 * - [QUERY]：查询侧。**本版没有文案、没有调用方** —— `V2-AI-PRD` §7 明确「本版不引入 AI
 *   查询」。留这个枚举位是为了让「录入 / 图片 / 查询」三档在类型上可见；
 *   §7 的三个问句有答案后，只需在 [AiPrompt] 里补一段功能段文案，其余四段不动。
 */
enum class AiScene {
    /** 录入 · 文字通道（`V2-FR-02`）。 */
    TEXT_INPUT,

    /** 录入 · 语音句通道（`V2-FR-10`；2026-10-09 由「与文字共用」独立成一个场景）。 */
    VOICE_INPUT,

    // 【2026-10-10 停用 · 注释保留】录音通道（音频随报文上行；平台不受理音频输入）：
    //     VOICE_AUDIO,

    /** 录入 · 照片通道（`V2-FR-11`）。 */
    PHOTO_INPUT,

    /** 查询侧（`V2-FR-16` 列出、`V2-AI-PRD` §7 本版不做文案）。 */
    QUERY,
}
